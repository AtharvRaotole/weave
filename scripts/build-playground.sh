#!/usr/bin/env bash
# Build the browser playground into a static site.
#
#   scripts/build-playground.sh [out_dir]     (default: target/playground-site)
#
# Needs the wasm32-unknown-unknown target and a wasm-bindgen CLI whose version
# matches the wasm-bindgen crate in Cargo.lock. Set WASM_BINDGEN to its path
# if it isn't on PATH.
set -euo pipefail
cd "$(dirname "$0")/.."
OUT="${1:-target/playground-site}"
BINDGEN="${WASM_BINDGEN:-wasm-bindgen}"

want=$(awk '/^name = "wasm-bindgen"$/{getline; gsub(/version = |"/, ""); print; exit}' Cargo.lock)
have=$("$BINDGEN" --version | awk '{print $2}')
if [ "$want" != "$have" ]; then
  echo "wasm-bindgen CLI is $have but Cargo.lock has $want" >&2
  exit 1
fi

CARGO_PROFILE_RELEASE_LTO=true \
CARGO_PROFILE_RELEASE_OPT_LEVEL=s \
CARGO_PROFILE_RELEASE_CODEGEN_UNITS=1 \
CARGO_PROFILE_RELEASE_PANIC=abort \
CARGO_TARGET_DIR=target/wasm-build \
  cargo build -p weave-wasm --release --target wasm32-unknown-unknown --locked

rm -rf "$OUT"
mkdir -p "$OUT/pkg"
"$BINDGEN" --target web --no-typescript --remove-name-section --remove-producers-section --out-dir "$OUT/pkg" \
  target/wasm-build/wasm32-unknown-unknown/release/weave_wasm.wasm

cp playground/index.html playground/style.css playground/app.js "$OUT/"
[ -f playground/og.png ] && cp playground/og.png "$OUT/"
python3 - "$OUT" <<'PY'
import json, pathlib, sys
src = pathlib.Path("playground/presets")
out = pathlib.Path(sys.argv[1])
items = json.loads((src / "manifest.json").read_text())
for item in items:
    item["code"] = (src / f"{item['id']}.weave").read_text()
(out / "presets.js").write_text(
    "// Generated by scripts/build-playground.sh from playground/presets.\n"
    "export const PRESETS = " + json.dumps(items, indent=2) + ";\n"
)
PY
touch "$OUT/.nojekyll"
echo "built $OUT ($(du -sh "$OUT" | cut -f1))"
